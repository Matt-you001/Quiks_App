export function getSubjectById(id?: string | string[], language: AppLanguage = "en") {
  if (!id || Array.isArray(id)) {
    return undefined;
  }

  return getLocalizedSubjects(language).find((subject) => subject.id === id);
}

export function getTopicById(subject: Subject | undefined, topicId?: string | string[]) {
  if (!subject || !topicId || Array.isArray(topicId)) {
    return undefined;
  }

  return subject.topics.find((topic) => topic.id === topicId);
}
