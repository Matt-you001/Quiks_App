function localizeTopicLabel(topic: SubjectTopic, language: AppLanguage) {
  const override = localizedTopicLabelOverrides[language]?.[topic.id];
  if (override) {
    return override;
  }

  const tokens = topic.id.split("-");
  const dictionary = topicTokenTranslations[language];
  if (!dictionary) {
    return topic.label;
  }

  const translated = tokens.map((token) => {
    if (dictionary[token]) {
      return dictionary[token];
    }

    return token
      .split(/(?=[A-Z])/)
      .join(" ")
      .replace(/^\w/, (char) => char.toUpperCase());
  });
  const changed = translated.some((token, index) => token !== tokens[index]);

  if (!changed) {
    return topic.label;
  }

  return translated.join(" / ");
}

function localizeTopic(topic: SubjectTopic, language: AppLanguage): SubjectTopic {
  const label = localizeTopicLabel(topic, language);
  const description =
    language === "en" ? topic.description : t(language, "topicPracticeDescription", { topic: label });

  return {
    ...topic,
    label,
    description,
  };
}

function localizeSubject(subject: Subject, language: AppLanguage) {
  const localized = localizedSubjectCopy[language]?.[subject.id];
  return {
    ...subject,
    name: appVariant.subjectNameOverrides?.[subject.id] ?? localized?.name ?? subject.name,
    tagline: localized?.tagline ?? subject.tagline,
    description: localized?.description ?? subject.description,
    topics: subject.topics.map((topic) => localizeTopic(topic, language)),
  };
}

